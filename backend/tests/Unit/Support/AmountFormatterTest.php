<?php

use App\Support\AmountFormatter;

// AmountFormatter::isValid が、旧(本番の laravel13)の Rules\Amount::$regex と同じ入力を受け付けるかを確かめる(#159)。
// 期待値は、旧のファイルをそのまま PHP 8.4 で読み込み、旧の正規表現に同じ入力を渡して出た値。

it('TC-159-34: 旧の正規表現が受け付ける量を受け付ける', function (string $amount) {
    expect(AmountFormatter::isValid($amount))->toBeTrue();
})->with([
    'TC-159-34: 整数' => ['30'],
    'TC-159-34: 1' => ['1'],
    'TC-159-34: 小数' => ['1.5'],
    'TC-159-34: 小数点で終わる' => ['10.'],
    'TC-159-34: 分数' => ['1/2'],
    'TC-159-34: t' => ['1t'],
    'TC-159-34: tsp' => ['1tsp'],
    'TC-159-34: m' => ['2m'],
    'TC-159-34: ml' => ['2ml'],
    'TC-159-34: oz' => ['1oz'],
    'TC-159-34: da' => ['1da'],
    'TC-159-34: dash' => ['1dash'],
    'TC-159-34: dr' => ['1dr'],
    'TC-159-34: drop' => ['1drop'],
    'TC-159-34: g' => ['10g'],
    'TC-159-34: 個' => ['1個'],
    'TC-159-34: 分数の個' => ['1/2個'],
    'TC-159-34: 片' => ['1片'],
    'TC-159-34: cup' => ['1cup'],
    'TC-159-34: 少量' => ['少量'],
    'TC-159-34: -' => ['-'],
    'TC-159-34: 適量' => ['適量'],
    'TC-159-34: 分母の無い分数(量に直すと例外になる)' => ['1/'],
    'TC-159-34: 分母が 0 の分数(量に直すと例外になる)' => ['2/0'],
]);

it('TC-159-35: 旧の正規表現が受け付けない量を受け付けない', function (string $amount) {
    expect(AmountFormatter::isValid($amount))->toBeFalse();
})->with([
    'TC-159-35: 0' => ['0'],
    'TC-159-35: 0 で始まる小数' => ['0.5'],
    'TC-159-35: c(書式では cup にする)' => ['1c'],
    'TC-159-35: 分数の c' => ['1/2c'],
    'TC-159-35: 枚(量に直すと 0 になる)' => ['1枚'],
    'TC-159-35: nothing' => ['nothing'],
    'TC-159-35: 空文字' => [''],
    'TC-159-35: 後ろに空白' => ['1 '],
    'TC-159-35: 英字だけ' => ['abc'],
    'TC-159-35: 指数' => ['1e3'],
    'TC-159-35: 区切りが 2 つ' => ['1/2/3'],
    'TC-159-35: 単位だけ' => ['ml'],
]);
