<?php

use App\Support\NameNormalizer;

// NameNormalizer が、旧の convert_to_name_search(旧の Markup と SearchCommon\Search に同じものがある)と
// 同じ結果を返すかを確かめる(#171)。期待値は、手元で動かした旧(PHP 7.4)で旧の関数に同じ入力を渡して出た値。

it('TC-171-01〜19: 旧の convert_to_name_search と同じ結果を返す', function (string $name, string $expected) {
    expect(NameNormalizer::normalize($name))->toBe($expected);
})->with([
    'TC-171-01: ひらがなはカタカナにしない' => ['じんとにっく', 'じんとにっく'],
    'TC-171-02: カタカナはそのまま' => ['ジントニック', 'ジントニック'],
    'TC-171-03: 半角カナは全角にしない' => ['ｼﾞﾝﾄﾆｯｸ', 'ｼﾞﾝﾄﾆｯｸ'],
    'TC-171-04: 全角の中黒を消す' => ['ジン・トニック', 'ジントニック'],
    'TC-171-05: 半角の中黒は残す' => ['ｼﾞﾝ･ﾄﾆｯｸ', 'ｼﾞﾝ･ﾄﾆｯｸ'],
    'TC-171-06: 半角の空白を消す' => ['ソルティ ドッグ', 'ソルティドッグ'],
    'TC-171-07: 全角の空白は残す' => ['ソルティ　ドッグ', 'ソルティ　ドッグ'],
    'TC-171-08: タブは残す' => ["ソルティ\tドッグ", "ソルティ\tドッグ"],
    'TC-171-09: 半角のピリオドを消す' => ['Mr.Boston', 'MrBoston'],
    'TC-171-10: 全角の英字は半角にし、全角のピリオドは残す' => ['Ｍｒ．Ｂｏｓｔｏｎ', 'Mr．Boston'],
    'TC-171-11: 大文字・小文字は変えない' => ['ＧＩＮ ｇｉｎ', 'GINgin'],
    'TC-171-12: 全角の数字を半角にする' => ['Ｎｏ．１２３', 'No．123'],
    'TC-171-13: 半角の英数字はそのまま(空白だけ消す)' => ['Gin 123', 'Gin123'],
    'TC-171-14: 全角の記号は半角にしない' => ['Ｂ＆Ｂ', 'B＆B'],
    'TC-171-15: 長音と全角のハイフンは残す' => ['ブルー・ムーン－ー', 'ブルームーン－ー'],
    'TC-171-16: 消す文字だけなら空文字になる' => ['・・ . .', ''],
    'TC-171-17: 空文字は空文字のまま' => ['', ''],
    'TC-171-18: 結合文字の濁点は合成しない' => ["シ\u{3099}ン", "シ\u{3099}ン"],
    'TC-171-19: 全角の括弧は残す' => ['ジン（ドライ）', 'ジン（ドライ）'],
]);

it('TC-171-20: 正規化した名前をもう一度正規化しても変わらない', function (string $name) {
    $once = NameNormalizer::normalize($name);

    expect(NameNormalizer::normalize($once))->toBe($once);
})->with([
    'ジン・トニック', 'ｼﾞﾝ･ﾄﾆｯｸ', 'ソルティ　ドッグ', 'Ｍｒ．Ｂｏｓｔｏｎ', 'Ｎｏ．１２３', 'Ｂ＆Ｂ', '・・ . .',
]);
